import json
import os
import re
from decimal import Decimal

import mysql.connector
from mysql.connector import Error


def obtener_conexion():
    host = os.getenv("DB_HOST", "localhost")
    puerto = int(os.getenv("DB_PORT", "3306"))
    # Render Postgres usa un host dpg- y el puerto 5432.
    # En la computadora, sin esas variables, sigue entrando a MySQL.
    if host.startswith("dpg-") or puerto == 5432:
        return obtener_conexion_postgres(host, puerto)
    return obtener_conexion_mysql(host, puerto)


def obtener_conexion_mysql(host, puerto):
    try:
        datos = {
            "host": host,
            "port": puerto,
            "user": os.getenv("DB_USER", "root"),
            "password": os.getenv("DB_PASSWORD", "12345678"),
            "database": os.getenv("DB_NAME", "tramite_claro"),
            "charset": "utf8mb4",
            "connection_timeout": 8,
        }
        if os.getenv("DB_SSL", "").strip().lower() in ("1", "true", "si", "yes"):
            datos["ssl_disabled"] = False
            datos["ssl_verify_cert"] = False
        conexion = mysql.connector.connect(**datos)
        if conexion.is_connected():
            print("✓ Conexión exitosa a la base de datos MySQL")
            return conexion
    except Error as error:
        print(f"✗ Error al conectar a MySQL: {error}")
        return None


def obtener_conexion_postgres(host, puerto):
    try:
        import psycopg2
    except ImportError:
        print("✗ Falta psycopg2 para conectar con PostgreSQL")
        return None
    try:
        conexion = psycopg2.connect(
            host=host,
            port=puerto,
            user=os.getenv("DB_USER", ""),
            password=os.getenv("DB_PASSWORD", ""),
            dbname=os.getenv("DB_NAME", "tramite_claro"),
            sslmode="prefer",
            connect_timeout=10,
        )
        print("✓ Conexión exitosa a la base de datos PostgreSQL")
        envoltura = ConexionPostgres(conexion)
        cargar_semilla(envoltura)
        return envoltura
    except Exception as error:
        print(f"✗ Error al conectar a PostgreSQL: {error}")
        return None


def cerrar_conexion(conexion):
    if conexion and conexion.is_connected():
        conexion.close()
        print("✓ Conexión cerrada correctamente")


def adaptar_postgres(sql):
    sql = re.sub(r"INT\s+UNSIGNED", "INTEGER", sql, flags=re.IGNORECASE)
    sql = re.sub(
        r"INTEGER\s+NOT\s+NULL\s+AUTO_INCREMENT",
        "INTEGER GENERATED BY DEFAULT AS IDENTITY",
        sql,
        flags=re.IGNORECASE,
    )
    sql = re.sub(r"TINYINT\(\d+\)", "SMALLINT", sql, flags=re.IGNORECASE)
    sql = re.sub(r"ENUM\([^)]*\)", "VARCHAR(50)", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\s+ON\s+UPDATE\s+CURRENT_TIMESTAMP", "", sql, flags=re.IGNORECASE)
    sql = re.sub(
        r"UNIQUE\s+KEY\s+\w+\s+\(([^)]+)\)",
        r"UNIQUE (\1)",
        sql,
        flags=re.IGNORECASE,
    )
    sql = re.sub(
        r"\)\s*ENGINE=InnoDB\b[^;]*",
        ")",
        sql,
        flags=re.IGNORECASE,
    )
    coincidencia = re.search(
        r"ON\s+DUPLICATE\s+KEY\s+UPDATE\s+(.+)$",
        sql,
        flags=re.IGNORECASE | re.DOTALL,
    )
    if coincidencia:
        cambios = re.sub(
            r"VALUES\((\w+)\)",
            r"EXCLUDED.\1",
            coincidencia.group(1),
            flags=re.IGNORECASE,
        )
        if "avance_correo" in sql:
            conflicto = "(correo, tramite_id)"
        else:
            conflicto = "(correo)"
        sql = re.sub(
            r"ON\s+DUPLICATE\s+KEY\s+UPDATE\s+.+$",
            f"ON CONFLICT {conflicto} DO UPDATE SET {cambios}",
            sql,
            flags=re.IGNORECASE | re.DOTALL,
        )
    return sql


def limpiar_valor(valor):
    if isinstance(valor, Decimal):
        return float(valor)
    if isinstance(valor, dict):
        return {clave: limpiar_valor(item) for clave, item in valor.items()}
    if isinstance(valor, tuple):
        return tuple(limpiar_valor(item) for item in valor)
    if isinstance(valor, list):
        return [limpiar_valor(item) for item in valor]
    return valor


class CursorPostgres:
    def __init__(self, cursor):
        self._cursor = cursor

    def execute(self, operacion, params=None):
        sql = adaptar_postgres(operacion)
        if params is None:
            return self._cursor.execute(sql)
        return self._cursor.execute(sql, params)

    def fetchone(self):
        return limpiar_valor(self._cursor.fetchone())

    def fetchall(self):
        return limpiar_valor(self._cursor.fetchall())

    def __getattr__(self, nombre):
        return getattr(self._cursor, nombre)


class ConexionPostgres:
    def __init__(self, conexion):
        self._conexion = conexion

    def cursor(self, dictionary=False):
        if dictionary:
            from psycopg2.extras import RealDictCursor
            cursor = self._conexion.cursor(cursor_factory=RealDictCursor)
        else:
            cursor = self._conexion.cursor()
        return CursorPostgres(cursor)

    def commit(self):
        self._conexion.commit()

    def rollback(self):
        self._conexion.rollback()

    def close(self):
        self._conexion.close()

    def is_connected(self):
        return self._conexion.closed == 0


def tipo_postgres(tipo_mysql):
    tipo = tipo_mysql.lower()
    if tipo.startswith("int"):
        return "INTEGER"
    if tipo.startswith("tinyint"):
        return "SMALLINT"
    if tipo.startswith("enum"):
        return "VARCHAR(50)"
    if tipo.startswith("varchar") or tipo.startswith("char") or tipo.startswith("decimal"):
        return tipo.upper().replace("DECIMAL", "NUMERIC")
    if tipo in ("text", "json", "date"):
        return tipo.upper()
    if tipo in ("timestamp", "datetime"):
        return "TIMESTAMP"
    return "TEXT"


def cargar_semilla(conexion):
    cursor = conexion.cursor()
    try:
        cursor.execute("SELECT to_regclass('public.tramites')")
        if cursor.fetchone()[0]:
            return
        ruta = os.path.join(os.path.dirname(os.path.abspath(__file__)), "semilla_postgres.json")
        with open(ruta, encoding="utf-8") as archivo:
            semilla = json.load(archivo)
        for tabla in semilla["tablas"]:
            columnas = []
            for columna in tabla["columnas"]:
                tipo = tipo_postgres(columna["tipo"])
                if columna["llave"] == "PRI":
                    columnas.append(
                        f"{columna['nombre']} INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
                    )
                    continue
                nulo = "" if columna["nulo"] else " NOT NULL"
                unico = " UNIQUE" if columna["llave"] == "UNI" else ""
                columnas.append(f"{columna['nombre']} {tipo}{nulo}{unico}")
            cursor.execute(
                f"CREATE TABLE IF NOT EXISTS {tabla['nombre']} ({', '.join(columnas)})"
            )
            nombres = [columna["nombre"] for columna in tabla["columnas"]]
            marcas = ", ".join(["%s"] * len(nombres))
            insertar = (
                f"INSERT INTO {tabla['nombre']} ({', '.join(nombres)}) VALUES ({marcas})"
            )
            from psycopg2.extras import Json
            tipos = [columna["tipo"].lower() for columna in tabla["columnas"]]
            for fila in tabla["filas"]:
                valores = []
                for tipo, valor in zip(tipos, fila):
                    if tipo == "json" and isinstance(valor, (dict, list)):
                        valores.append(Json(valor))
                    elif tipo == "json" and isinstance(valor, str):
                        valores.append(Json(json.loads(valor)))
                    else:
                        valores.append(valor)
                cursor.execute(insertar, valores)
            cursor.execute(
                f"SELECT setval(pg_get_serial_sequence('{tabla['nombre']}', 'id'), "
                f"COALESCE((SELECT MAX(id) FROM {tabla['nombre']}), 1))"
            )
        conexion.commit()
        print("✓ Trámites cargados en PostgreSQL")
    except Exception as error:
        conexion.rollback()
        print(f"✗ Error al cargar los trámites en PostgreSQL: {error}")
    finally:
        cursor.close()
